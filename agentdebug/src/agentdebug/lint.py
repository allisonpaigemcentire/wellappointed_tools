@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    rule_id: str
    message: str
    hint: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


def lint_path(path: Path) -> list[Finding]:
    """Lint a Python file or walk a directory. Findings are sorted and stable."""
    target = path.expanduser()
    if not target.exists():
        raise FileNotFoundError(target)
    files = _python_files(target)
    findings: list[Finding] = []
    for file_path in files:
        findings.extend(_lint_file(file_path))
    findings.sort(key=lambda item: (item.path, item.line, item.rule_id))
    return findings


def _python_files(target: Path) -> list[Path]:
    if target.is_file():
        return [target] if target.suffix == ".py" else []
    found: list[Path] = []
    for file_path in target.rglob("*.py"):
        if any(part in SKIP_DIRS for part in file_path.parts):
            continue
        found.append(file_path)
    return sorted(found)


def _lint_file(path: Path) -> list[Finding]:
    display = _display(path)
    try:
        source = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return [
            Finding(
                path=display,
                line=1,
                rule_id="AGT000",
                message="file is not valid UTF-8",
                hint="Save the file as UTF-8, or exclude generated bytes from the scan.",
            )
        ]
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as exc:
        return [
            Finding(
                path=display,
                line=exc.lineno or 1,
                rule_id="AGT000",
                message=f"could not parse file: {exc.msg}",
                hint="Fix the syntax error so the other rules can run.",
            )
        ]
    _attach_parents(tree)
    findings: list[Finding] = []
    findings.extend(_swallowed_exceptions(tree, display))
    findings.extend(_hardcoded_gates(tree, display))
    findings.extend(_unbounded_loops(tree, display))
    findings.extend(_retry_decorators(tree, display))
    findings.extend(_silent_truncation(tree, display))
    findings.extend(_missing_timeouts(tree, display))
    findings.extend(_ungated_write_tools(tree, display))
    findings.extend(_secrets(tree, display))
    return findings


def _display(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        return resolved.as_posix()


def _attach_parents(tree: ast.AST) -> None:
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            child.parent = node  # type: ignore[attr-defined]


def _swallowed_exceptions(tree: ast.AST, display: str) -> list[Finding]:
    """AGT001: handlers that hide an error, including a broad except that returns an empty value."""
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ExceptHandler):
            continue
        bare = node.type is None
        only_pass = _handler_is_pass(node)
        silent_empty = _is_broad_handler(node) and _handler_returns_empty(node)
        if not bare and not only_pass and not silent_empty:
            continue
        if bare and only_pass:
            message = "bare except whose body is only pass"
        elif bare:
            message = "bare except swallows every failure, including interrupts"
        elif only_pass:
            message = "exception handler body is only pass"
        else:
            message = "broad except turns a failure into an empty result"
        findings.append(
            Finding(
                path=display,
                line=node.lineno,
                rule_id="AGT001",
                message=message,
                hint="Log the failure and re-raise, or catch a specific error and record it on the trace.",
            )
        )
    return findings


def _handler_is_pass(node: ast.ExceptHandler) -> bool:
    if not node.body:
        return False
    return all(_is_noop(stmt) for stmt in node.body)


def _is_broad_handler(node: ast.ExceptHandler) -> bool:
    """True for a bare except or one that catches Exception or BaseException."""
    if node.type is None:
        return True
    names = node.type.elts if isinstance(node.type, ast.Tuple) else [node.type]
    return any(_chain(name)[-1:] and _chain(name)[-1] in _BROAD_EXCEPTIONS for name in names)


def _handler_returns_empty(node: ast.ExceptHandler) -> bool:
    """The body is only `return <empty>`, `return None`, or `continue`, with no log and no raise."""
    if not node.body:
        return False
    body = [stmt for stmt in node.body if not _is_noop(stmt)]
    if len(body) != 1:
        return False
    stmt = body[0]
    if isinstance(stmt, ast.Continue):
        return True
    return isinstance(stmt, ast.Return) and _is_empty_value(stmt.value)


def _is_empty_value(node: ast.AST | None) -> bool:
    """True when a returned value is empty: None or an empty literal."""
    if node is None:
        return True
    if isinstance(node, ast.Constant):
        # False is left out: `except Exception: return False` in a validity check is the
        # check's answer, not an empty result standing in for real data.
        return node.value is None or node.value in ("", b"")
    if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        return not node.elts
    if isinstance(node, ast.Dict):
        return not node.keys
    if isinstance(node, ast.Call) and not node.args and not node.keywords:
        return isinstance(node.func, ast.Name) and node.func.id in {"list", "dict", "set", "tuple", "str"}
    return False


def _is_noop(stmt: ast.stmt) -> bool:
    if isinstance(stmt, ast.Pass):
        return True
    if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and stmt.value.value is Ellipsis:
        return True
    return False


def _hardcoded_gates(tree: ast.AST, display: str) -> list[Finding]:
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and _always_true_gate(node):
            findings.append(
                Finding(
                    path=display,
                    line=node.lineno,
                    rule_id="AGT002",
                    message=f"{node.name} returns True on every path",
                    hint="Grade the final state, or return False when the check fails. A constant True gate hides the bug.",
                )
            )
        elif isinstance(node, ast.Call) and _call_is_hardcoded_pass(node):
            findings.append(
                Finding(
                    path=display,
                    line=node.lineno,
                    rule_id="AGT002",
                    message="gate call hard-codes a passing result",
                    hint="Set passed from the findings you actually computed. Do not ship an empty findings list with passed=True.",
                )
            )
        elif isinstance(node, ast.Dict) and _dict_is_hardcoded_pass(node):
            findings.append(
                Finding(
                    path=display,
                    line=node.lineno,
                    rule_id="AGT002",
                    message="result dict hard-codes passed=True with empty findings",
                    hint="Build passed from the finding list so an empty list is a real pass, not a constant.",
                )
            )
    return findings


def _always_true_gate(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    if not _GATE_FUNCTION.match(fn.name):
        return False
    returns = _returns(fn.body)
    if not returns:
        return False
    return all(_is_true_constant(node.value) for node in returns if node.value is not None) and all(
        node.value is not None for node in returns
    )


def _returns(body: list[ast.stmt]) -> list[ast.Return]:
    found: list[ast.Return] = []
    for stmt in body:
        found.extend(_returns_in(stmt))
    return found


def _returns_in(stmt: ast.AST) -> list[ast.Return]:
    if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
        return []
    if isinstance(stmt, ast.Return):
        return [stmt]
    found: list[ast.Return] = []
    for child in ast.iter_child_nodes(stmt):
        found.extend(_returns_in(child))
    return found


def _call_is_hardcoded_pass(node: ast.Call) -> bool:
    keywords = _keywords(node)
    passed = any(_is_true_constant(keywords.get(name)) for name in ("passed", "success", "ok"))
    if not passed:
        return False
    empty_findings = any(
        name in keywords and _is_empty_list(keywords[name]) for name in ("findings", "errors", "violations")
    )
    callee = _chain(node.func)
    name = callee[-1] if callee else ""
    looks_like_gate = bool(re.search(r"(?i)(gate|verdict|qa|check)", name))
    return empty_findings or looks_like_gate


def _dict_is_hardcoded_pass(node: ast.Dict) -> bool:
    pairs = _dict_pairs(node)
    passed = any(_is_true_constant(pairs.get(name)) for name in ("passed", "success", "ok"))
    empty = any(name in pairs and _is_empty_list(pairs[name]) for name in ("findings", "errors", "violations"))
    return passed and empty


def _unbounded_loops(tree: ast.AST, display: str) -> list[Finding]:
    """AGT003 and AGT004: `while True` loops that call a model, a tool, or a retry with no cap that ends the loop."""
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.While):
            continue
        if not _is_true_constant(node.test):
            continue
        if _has_iteration_cap(node):
            continue
        calls = [item for item in ast.walk(node) if isinstance(item, ast.Call)]
        has_agent_call = any(_is_llm_or_tool_call(call) for call in calls)
        has_retry = any(_try_retries_a_call(item) for item in ast.walk(node) if isinstance(item, ast.Try))
        if has_agent_call:
            findings.append(
                Finding(
                    path=display,
                    line=node.lineno,
                    rule_id="AGT003",
                    message="while True calls a model or tool with no max-iteration cap",
                    hint="Stop after a max turn, token, or tool-call budget and escalate to a person.",
                )
            )
        if has_retry:
            findings.append(
                Finding(
                    path=display,
                    line=node.lineno,
                    rule_id="AGT004",
                    message="retry loop has no attempt limit",
                    hint="Count attempts and stop at a fixed max. Record the last error instead of looping.",
                )
            )
    return findings


def _try_retries_a_call(node: ast.Try) -> bool:
    """A try/except is a retry when the try body calls a model, a tool, or an HTTP client.

    An event loop that catches a queue or parse error and moves on is not a retry.
    """
    if not node.handlers:
        return False
    for stmt in node.body:
        for item in ast.walk(stmt):
            if isinstance(item, ast.Call) and (_is_llm_or_tool_call(item) or _is_network_call(item)):
                return True
    return False


def _is_network_call(node: ast.Call) -> bool:
    """True when the call looks like an HTTP request or urlopen."""
    parts = _strip_self(_chain(node.func))
    if not parts:
        return False
    if parts[-1] == "urlopen":
        return True
    return parts[-1] in _HTTP_METHODS and _looks_like_http(parts)


def _retry_decorators(tree: ast.AST, display: str) -> list[Finding]:
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for deco in node.decorator_list:
            if not _is_unlimited_retry(deco):
                continue
            findings.append(
                Finding(
                    path=display,
                    line=getattr(deco, "lineno", node.lineno),
                    rule_id="AGT004",
                    message=f"{node.name} retries without a visible stop condition",
                    hint="Pass a stop, max_attempts, or equivalent limit into the retry decorator.",
                )
            )
    return findings


def _is_unlimited_retry(deco: ast.AST) -> bool:
    target = deco.func if isinstance(deco, ast.Call) else deco
    parts = _chain(target)
    if not parts:
        return False
    name = parts[-1].lower()
    if name != "retry" and not name.endswith("retry"):
        return False
    if not isinstance(deco, ast.Call):
        return True
    return not _call_expresses_limit(deco)


def _call_expresses_limit(node: ast.Call) -> bool:
    for keyword in node.keywords:
        if keyword.arg and re.search(r"(?i)(stop|max|attempt|limit|cap)", keyword.arg):
            return True
    for arg in list(node.args) + [kw.value for kw in node.keywords]:
        for child in ast.walk(arg):
            if isinstance(child, ast.Call):
                chain = _chain(child.func)
                label = chain[-1] if chain else ""
                if re.search(r"(?i)(stop|max|attempt|limit)", label):
                    return True
            if isinstance(child, ast.Name) and re.search(r"(?i)(stop|max|attempt|limit)", child.id):
                return True
    return False


def _has_iteration_cap(loop: ast.While) -> bool:
    """A cap is a comparison in the loop test, or an `if` that compares and then leaves the loop.

    A cap-like name anywhere else in the body (for example `max_tokens=` on the model
    call) does not stop the loop, so it does not count.
    """
    if _test_is_counter_cap(loop.test):
        return True
    for node, nested in _loop_body_nodes(loop.body, nested=False):
        if isinstance(node, ast.If) and _if_exits(node, nested) and _test_is_counter_cap(node.test):
            return True
    return False


_LOOPS = (ast.For, ast.AsyncFor, ast.While)
_SCOPES = (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)


def _loop_body_nodes(body: list[ast.stmt], nested: bool):
    """Yield (node, nested) for nodes under a loop body.

    `nested` is True once the walk is inside an inner loop, where a `break`
    leaves the inner loop and not this one. Nested functions and classes are
    not walked: their code does not run as part of this loop.
    """
    stack: list[tuple[ast.AST, bool]] = [(stmt, nested) for stmt in reversed(body)]
    while stack:
        node, inner = stack.pop()
        if isinstance(node, _SCOPES):
            continue
        yield node, inner
        child_inner = inner or isinstance(node, _LOOPS)
        for child in reversed(list(ast.iter_child_nodes(node))):
            stack.append((child, child_inner))


def _is_elif(node: ast.If) -> bool:
    """True when the else branch is just an `elif`."""
    return len(node.orelse) == 1 and isinstance(node.orelse[0], ast.If)


def _if_exits(node: ast.If, nested: bool = False) -> bool:
    """True when the if or else body leaves the loop: return or raise, or a break that is not inside an inner loop."""
    # An `else: break` leaves the loop too. An `elif` is its own If node and is checked on its own.
    branches = node.body if _is_elif(node) else node.body + node.orelse
    for item, inner in _loop_body_nodes(branches, nested):
        if isinstance(item, (ast.Return, ast.Raise)):
            return True
        if isinstance(item, ast.Break) and not inner:
            return True
    return False


def _cap_name(name: str) -> bool:
    """True for a name that reads as an iteration cap, not a token limit such as max_tokens."""
    # Split camelCase so maxTurns reads as max_Turns and maxOutputTokens as a token limit.
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return bool(_MAX_NAME.search(name)) and not _TOKEN_LIMIT_NAME.search(name)


def _compare_names(test: ast.AST) -> list[str]:
    """Names and attribute names used anywhere in a test expression."""
    names: list[str] = []
    for item in ast.walk(test):
        if isinstance(item, ast.Name):
            names.append(item.id)
        elif isinstance(item, ast.Attribute):
            names.append(item.attr)
        elif (
            isinstance(item, ast.Subscript)
            and isinstance(item.slice, ast.Constant)
            and isinstance(item.slice.value, str)
        ):
            # config["max_turns"] names its cap with a string key.
            names.append(item.slice.value)
    return names


def _test_is_counter_cap(test: ast.AST) -> bool:
    """True when a test compares a counter against an iteration cap."""
    if isinstance(test, ast.BoolOp):
        return any(_test_is_counter_cap(value) for value in test.values)
    if not isinstance(test, ast.Compare):
        # `if budget.exhausted():` or `if not limits.ok(turn):` checks a cap without a comparison.
        return any(_cap_name(name) for name in _compare_names(test))
    names = _compare_names(test)
    has_counter = any(_COUNTER_NAME.match(name) for name in names)
    has_cap = any(_cap_name(name) for name in names)
    has_int = any(
        isinstance(item, ast.Constant) and isinstance(item.value, int) and not isinstance(item.value, bool)
        for item in ast.walk(test)
    )
    return (has_counter or has_cap) and (has_int or has_cap)


def _silent_truncation(tree: ast.AST, display: str) -> list[Finding]:
    """AGT005: prefix slices of model or tool text that are not just logged."""
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Subscript) or not isinstance(node.slice, ast.Slice):
            continue
        if not _is_prefix_slice(node.slice):
            continue
        target = _slice_name(node.value)
        if target is None or target.lower() not in _TRUNCATED_NAMES:
            continue
        if _inside_log_call(node):
            continue
        findings.append(
            Finding(
                path=display,
                line=node.lineno,
                rule_id="AGT005",
                message=f"{target}[:N] drops the tail of a prompt or model input",
                hint="Chunk the input and record that it was cut. A silent prefix slice hides the ending from the model.",
            )
        )
    return findings


def _inside_log_call(node: ast.AST) -> bool:
    """A slice passed to print, a logger, or a stream write is a preview, not model input."""
    current = getattr(node, "parent", None)
    while current is not None and not isinstance(current, ast.stmt):
        if isinstance(current, ast.Call) and _is_log_call(current):
            return True
        current = getattr(current, "parent", None)
    return False


def _is_log_call(node: ast.Call) -> bool:
    """True for print, a logger call, or a write to sys.stdout or sys.stderr."""
    parts = _strip_self(_chain(node.func))
    if not parts:
        return False
    if parts == ["print"]:
        return True
    if _is_std_stream_write(parts):
        return True
    lower = [part.lower() for part in parts]
    return len(lower) >= 2 and (lower[0] in _LOG_ROOTS or lower[-2].endswith(("log", "logger"))) and lower[-1] in _LOG_METHODS


def _is_std_stream_write(parts: list[str]) -> bool:
    """True for a sys.stdout or sys.stderr method call."""
    return len(parts) >= 3 and parts[0] == "sys" and parts[1] in _STD_STREAMS


def _is_prefix_slice(node: ast.Slice) -> bool:
    if node.upper is None:
        return False
    if node.lower is None:
        return True
    return isinstance(node.lower, ast.Constant) and node.lower.value == 0


def _slice_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _missing_timeouts(tree: ast.AST, display: str) -> list[Finding]:
    """AGT006: network calls with no timeout, unless the client was built with one."""
    findings: list[Finding] = []
    covered = _clients_with_timeout(tree)
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        if _has_keyword(node, "timeout"):
            continue
        if not _needs_timeout(node):
            continue
        parts = _strip_self(_chain(node.func))
        if parts and parts[0] in covered:
            continue
        label = ".".join(_chain(node.func)) or "call"
        findings.append(
            Finding(
                path=display,
                line=node.lineno,
                rule_id="AGT006",
                message=f"{label} has no timeout",
                hint="Pass timeout=... on HTTP and model calls so a hung client cannot stall the agent.",
            )
        )
    return findings


def _clients_with_timeout(tree: ast.AST) -> set[str]:
    """Names bound in this module to a client built with timeout=, such as `client = OpenAI(timeout=30)`."""
    covered: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            targets, value = node.targets, node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets, value = [node.target], node.value
        else:
            continue
        if not isinstance(value, ast.Call) or not _has_real_timeout(value):
            continue
        for target in targets:
            parts = _strip_self(_chain(target))
            if len(parts) == 1:
                covered.add(parts[0])
    return covered


def _has_real_timeout(node: ast.Call) -> bool:
    """True when the call passes timeout= with a value other than None. timeout=None turns timeouts off."""
    for keyword in node.keywords:
        if keyword.arg == "timeout":
            return not (isinstance(keyword.value, ast.Constant) and keyword.value.value is None)
    return False


def _strip_self(parts: list[str]) -> list[str]:
    """Drop a leading self or cls from a call chain."""
    if len(parts) > 1 and parts[0] in _SELF_NAMES:
        return parts[1:]
    return parts


def _needs_timeout(node: ast.Call) -> bool:
    """True when the call is a network request that should carry a timeout."""
    parts = _strip_self(_chain(node.func))
    if not parts:
        return False
    last = parts[-1]
    lower_parts = [part.lower() for part in parts]
    if last == "urlopen":
        return True
    if last in _HTTP_CONSTRUCTORS and (
        "httpx" in lower_parts or "requests" in lower_parts or lower_parts[0] in {"httpx", "requests"}
    ):
        return True
    if last in _HTTP_METHODS and _looks_like_http(parts):
        return True
    if last in _LLM_CALL_NAMES and any(part.lower() in _LLM_CONTEXT for part in parts[:-1]):
        return True
    return False


def _looks_like_http(parts: list[str]) -> bool:
    lower = [part.lower() for part in parts]
    if "requests" in lower or "httpx" in lower or "urllib" in lower:
        return True
    root = lower[0]
    return root in _HTTP_ROOTS


def _ungated_write_tools(tree: ast.AST, display: str) -> list[Finding]:
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if not _is_tool(node):
            continue
        if _has_approval(node):
            continue
        if not _writes_or_sends(node):
            continue
        findings.append(
            Finding(
                path=display,
                line=node.lineno,
                rule_id="AGT007",
                message=f"{node.name} writes or sends without an approval flag",
                hint="Add an approval parameter and refuse the call until a person has allowed that write.",
            )
        )
    return findings


def _is_tool(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    """True when the function is a tool by name or by its decorator."""
    if _is_tool_name(fn.name):
        return True
    for deco in fn.decorator_list:
        target = deco.func if isinstance(deco, ast.Call) else deco
        # Any part of the decorator counts: @tool, @mcp.tool(), @function_tool,
        # and @tool_registry.register.
        if any(_is_tool_name(part) for part in _chain(target)):
            return True
    return False


def _is_tool_name(name: str) -> bool:
    """True when `tool` is a whole segment of a snake_case or camelCase name."""
    return bool(_TOOL_NAME.search(name) or _TOOL_CAMEL.search(name))


def _has_approval(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    names = [arg.arg for arg in list(fn.args.args) + list(fn.args.kwonlyargs)]
    if any(_APPROVAL_NAME.search(name) for name in names):
        return True
    for node in ast.walk(fn):
        if isinstance(node, ast.Name) and _APPROVAL_NAME.search(node.id):
            return True
    return False


def _writes_or_sends(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    """True when the function writes, sends, or deletes, ignoring stdout and stderr writes."""
    if re.match(r"(?i)^(send|write|delete|publish|email|post|execute|remove)_", fn.name):
        return True
    for node in ast.walk(fn):
        if isinstance(node, ast.Call):
            parts = _chain(node.func)
            if parts and _is_std_stream_write(parts):
                continue
            if parts and parts[-1] in _WRITE_CALLS:
                return True
            if parts and parts[-1] == "open":
                mode = _open_mode(node)
                if mode is not None and any(flag in mode for flag in ("w", "a", "x", "+")):
                    return True
        if isinstance(node, ast.Attribute) and node.attr in _WRITE_CALLS and not _is_std_stream_write(_chain(node)):
            return True
    return False


def _open_mode(node: ast.Call) -> str | None:
    if len(node.args) >= 2 and isinstance(node.args[1], ast.Constant) and isinstance(node.args[1].value, str):
        return node.args[1].value
    for keyword in node.keywords:
        if keyword.arg == "mode" and isinstance(keyword.value, ast.Constant) and isinstance(keyword.value.value, str):
            return keyword.value.value
    return None


def _secrets(tree: ast.AST, display: str) -> list[Finding]:
    """AGT008: string constants that look like API keys or tokens."""
    findings: list[Finding] = []
    seen: set[int] = set()
    prefix = _secret_prefix()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        if isinstance(getattr(node, "parent", None), ast.Expr):
            continue
        if prefix.search(node.value):
            findings.append(_secret_finding(display, node.lineno, "string looks like a live credential"))
            seen.add(node.lineno)
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            targets = node.targets
            value = node.value
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
            value = node.value
        else:
            continue
        if value is None or not isinstance(value, ast.Constant) or not isinstance(value.value, str):
            continue
        if value.lineno in seen:
            continue
        if not any(_target_is_secret(target) for target in targets):
            continue
        if not _assigned_secret(value.value):
            continue
        findings.append(_secret_finding(display, value.lineno, "secret-like name is assigned a string literal"))
        seen.add(value.lineno)
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for arg, default in _args_with_defaults(node.args):
            if default is None or not isinstance(default, ast.Constant) or not isinstance(default.value, str):
                continue
            if default.lineno in seen:
                continue
            if not _SECRET_NAME.search(arg.arg):
                continue
            if not _assigned_secret(default.value) and not prefix.search(default.value):
                continue
            findings.append(_secret_finding(display, default.lineno, f"default for {arg.arg} is a string literal"))
            seen.add(default.lineno)
    return findings


def _args_with_defaults(spec: ast.arguments) -> list[tuple[ast.arg, ast.expr | None]]:
    """Pair each parameter that has a default with that default.

    `defaults` belongs to the last positional parameters, positional-only ones
    included, as in `def f(key="x", /)`. `kw_defaults` lines up with
    `kwonlyargs` and holds None where a keyword-only parameter has no default.
    """
    positional = list(spec.posonlyargs) + list(spec.args)
    count = len(spec.defaults)
    pairs: list[tuple[ast.arg, ast.expr | None]] = []
    if count:
        pairs += list(zip(positional[-count:], spec.defaults, strict=True))
    pairs += list(zip(spec.kwonlyargs, spec.kw_defaults, strict=True))
    return pairs


def _secret_finding(display: str, line: int, message: str) -> Finding:
    return Finding(
        path=display,
        line=line,
        rule_id="AGT008",
        message=message,
        hint="Read secrets from the environment at runtime. Do not commit tokens, keys, or passwords.",
    )


def _target_is_secret(target: ast.AST) -> bool:
    if isinstance(target, ast.Name):
        return bool(_SECRET_NAME.search(target.id))
    if isinstance(target, ast.Attribute):
        return bool(_SECRET_NAME.search(target.attr))
    if isinstance(target, (ast.Tuple, ast.List)):
        return any(_target_is_secret(item) for item in target.elts)
    return False


def _assigned_secret(value: str) -> bool:
    if len(value) < 12:
        return False
    if _SAFE_SECRET.search(value):
        return False
    return True


def _secret_prefix() -> re.Pattern[str]:
    """High-confidence credential shapes. Pieces are split so this file is not itself a secret."""
    parts = [
        # OpenAI keys: legacy sk-<letters and digits>, and the current sk-proj-, sk-svcacct-,
        # and sk-admin- shapes, whose bodies also use - and _. The lookbehind keeps
        # "desk-lamp-checkout-flow" and "risk-assessment-report" from matching.
        r"(?<![A-Za-z0-9_\-])" + "sk" + r"\-" + r"(?:(?:proj|svcacct|admin)\-[A-Za-z0-9_\-]{16,}|[A-Za-z0-9]{16,})",
        r"(?<![A-Za-z0-9_\-])" + "sk" + r"\-" + "ant" + r"\-",
        "gh" + "p_",
        "gh" + "o_",
        "github_" + "pat_",
        "xo" + r"x[baprs]\-",
        "AK" + "IA" + r"[0-9A-Z]{16}",
        "AI" + "za" + r"[0-9A-Za-z_\-]{20,}",
        "-----BE" + "GIN " + r"[A-Z ]+" + "PRIVATE KEY" + "-----",
    ]
    return re.compile("|".join(parts))


def _is_llm_or_tool_call(node: ast.Call) -> bool:
    if isinstance(node.func, ast.Name) and _DIRECT_LLM.match(node.func.id):
        return True
    parts = _chain(node.func)
    if not parts:
        return False
    last = parts[-1]
    if last in _LLM_CALL_NAMES and any(part.lower() in _LLM_CONTEXT for part in parts[:-1]):
        return True
    if last in {"run", "call", "__call__"} and any(part.lower() in {"llm", "tool", "agent"} for part in parts[:-1]):
        return True
    if last in {"call_tool", "use_tool", "execute_tool", "run_agent"}:
        return True
    return False


def _chain(node: ast.AST) -> list[str]:
    parts: list[str] = []
    current: ast.AST | None = node
    while isinstance(current, ast.Attribute):
        parts.append(current.attr)
        current = current.value
    if isinstance(current, ast.Name):
        parts.append(current.id)
    elif isinstance(current, ast.Call):
        inner = _chain(current.func)
        if inner:
            parts.append(inner[-1])
    parts.reverse()
    return parts


def _keywords(node: ast.Call) -> dict[str, ast.AST]:
    return {keyword.arg: keyword.value for keyword in node.keywords if keyword.arg}


def _has_keyword(node: ast.Call, name: str) -> bool:
    return any(keyword.arg == name for keyword in node.keywords)


def _dict_pairs(node: ast.Dict) -> dict[str, ast.AST]:
    """String keys of a dict literal mapped to their values."""
    pairs: dict[str, ast.AST] = {}
    for key, value in zip(node.keys, node.values, strict=True):
        if isinstance(key, ast.Constant) and isinstance(key.value, str) and value is not None:
            pairs[key.value] = value
    return pairs


def _is_true_constant(node: ast.AST | None) -> bool:
    if node is None:
        return False
    if isinstance(node, ast.Constant):
        return node.value is True
    if isinstance(node, ast.Name):
        return node.id == "True"
    return False


def _is_empty_list(node: ast.AST) -> bool:
    return isinstance(node, ast.List) and not node.elts
